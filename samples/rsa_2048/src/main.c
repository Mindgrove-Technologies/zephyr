        ret = api->invoke(dev, RSA_MG_OP_VERIFY, RSA_MG_PAD_PKCS_V15, &pkt);

        /* Determine if the outcome matches the KAT requirement */
        bool is_success = false;
        if (tv->expected_result == 'P' && ret == 0) {
            is_success = true;
        } else if (tv->expected_result == 'F' && ret != 0) {
            is_success = true;
        }

