        const rsa_verif_test_vectors *tv = &verif_kat_vectors[i];
        struct rsa_mg_pkt pkt;
        int ret;

        /* * Parameter Check & Mapping:
         * .in      -> The 256-byte signature provided by the test vector.
         * .out     -> The message/hash data we expect to find inside the signature.
         * .out_len -> Converting bits to bytes for the hashing logic.
         */
        pkt.in      = (uint8_t *)tv->signature;
